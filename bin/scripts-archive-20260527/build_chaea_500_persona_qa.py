def validate(entries: list[dict[str, str]]) -> list[str]:
    issues: list[str] = []
    if len(entries) != 500:
        issues.append(f"expected 500 entries, got {len(entries)}")
    questions = [e["question"] for e in entries]
    if len(set(questions)) != len(questions):
        issues.append("duplicate questions found")
    text = "\n".join(e["question"] + "\n" + e["answer"] for e in entries)
    banned = ["신채아", "SHIN", "Shin", "한국어가 어려워요", "제가 한국말이 서툴러서요", "저는 사람입니다", "팬덤명은 채아라인"]
    for item in banned:
        if item in text:
            issues.append(f"banned phrase found: {item}")
    category_counts = {name: 0 for _, name, _ in CATEGORIES}
    for e in entries:
        category_counts[e["category"]] += 1
    for name, count in category_counts.items():
        if count != 50:
            issues.append(f"{name} count is {count}, expected 50")
    return issues


def set_cell_shading(cell, fill: str) -> None:
    tc_pr = cell._tc.get_or_add_tcPr()
    shd = OxmlElement("w:shd")
    shd.set(qn("w:fill"), fill)
    tc_pr.append(shd)


def set_cell_margins(cell, top=80, start=120, bottom=80, end=120) -> None:
    tc = cell._tc
    tc_pr = tc.get_or_add_tcPr()
    tc_mar = tc_pr.first_child_found_in("w:tcMar")
    if tc_mar is None:
        tc_mar = OxmlElement("w:tcMar")
        tc_pr.append(tc_mar)
    for m, v in {"top": top, "start": start, "bottom": bottom, "end": end}.items():
        node = tc_mar.find(qn(f"w:{m}"))
        if node is None:
            node = OxmlElement(f"w:{m}")
            tc_mar.append(node)
        node.set(qn("w:w"), str(v))
        node.set(qn("w:type"), "dxa")


def set_table_borders(table, color="DADCE0", size="4") -> None:
    tbl = table._tbl
    tbl_pr = tbl.tblPr
    borders = tbl_pr.first_child_found_in("w:tblBorders")
    if borders is None:
        borders = OxmlElement("w:tblBorders")
        tbl_pr.append(borders)
    for edge in ("top", "left", "bottom", "right", "insideH", "insideV"):
        tag = f"w:{edge}"
        element = borders.find(qn(tag))
        if element is None:
            element = OxmlElement(tag)
            borders.append(element)
        element.set(qn("w:val"), "single")
        element.set(qn("w:sz"), size)
        element.set(qn("w:space"), "0")
        element.set(qn("w:color"), color)


def set_run_font(run, east_asia="Apple SD Gothic Neo", latin="Arial") -> None:
    run.font.name = latin
    run._element.rPr.rFonts.set(qn("w:eastAsia"), east_asia)


def set_paragraph_font(paragraph, size=None, color=None, bold=None) -> None:
    for run in paragraph.runs:
        set_run_font(run)
        if size:
            run.font.size = Pt(size)
        if color:
            run.font.color.rgb = RGBColor.from_string(color)
        if bold is not None:
            run.bold = bold


def add_kv_table(doc: Document, rows: list[tuple[str, str]]) -> None:
    table = doc.add_table(rows=1, cols=2)
    table.alignment = WD_TABLE_ALIGNMENT.CENTER
    table.autofit = False
    table.columns[0].width = Inches(1.55)
    table.columns[1].width = Inches(4.7)
    set_table_borders(table)
    hdr = table.rows[0].cells
    hdr[0].text = "항목"
    hdr[1].text = "내용"
    for cell in hdr:
        set_cell_shading(cell, "E8EEF5")
        set_cell_margins(cell)
        cell.vertical_alignment = WD_CELL_VERTICAL_ALIGNMENT.CENTER
        set_paragraph_font(cell.paragraphs[0], 9.5, "1F4D78", True)
    for key, value in rows:
        cells = table.add_row().cells
        cells[0].text = key
        cells[1].text = value
        for cell in cells:
            set_cell_margins(cell)
            cell.vertical_alignment = WD_CELL_VERTICAL_ALIGNMENT.CENTER
            set_paragraph_font(cell.paragraphs[0], 9.2, "202326", None)


def configure_styles(doc: Document) -> None:
    section = doc.sections[0]
    section.top_margin = Inches(1)
    section.right_margin = Inches(1)
    section.bottom_margin = Inches(1)
    section.left_margin = Inches(1)
    section.header_distance = Inches(0.492)
    section.footer_distance = Inches(0.492)

    styles = doc.styles
    normal = styles["Normal"]
    normal.font.name = "Arial"
    normal._element.rPr.rFonts.set(qn("w:eastAsia"), "Apple SD Gothic Neo")
    normal.font.size = Pt(10.5)
    normal.paragraph_format.space_after = Pt(5)
    normal.paragraph_format.line_spacing = 1.2

    for name, size, color, before, after in [
        ("Title", 24, "0B2545", 0, 12),
        ("Heading 1", 16, "2E74B5", 18, 8),
        ("Heading 2", 13, "2E74B5", 14, 7),
        ("Heading 3", 11.5, "1F4D78", 10, 5),
    ]:
        style = styles[name]
        style.font.name = "Arial"
        style._element.rPr.rFonts.set(qn("w:eastAsia"), "Apple SD Gothic Neo")
        style.font.size = Pt(size)
        style.font.color.rgb = RGBColor.from_string(color)
        style.font.bold = True
        style.paragraph_format.space_before = Pt(before)
        style.paragraph_format.space_after = Pt(after)
        style.paragraph_format.line_spacing = 1.15


