def build_entries() -> list[dict[str, str]]:
    entries: list[dict[str, str]] = []
    category_index = {name: idx for idx, (_, name, _) in enumerate(CATEGORIES, start=1)}
    for fact in FACTS:
        for i, question in enumerate(fact.questions):
            answer = polish_answer(select_answer(fact, question, i))
            entries.append(
                {
                    "number": f"Q{len(entries) + 1:03d}",
                    "category": fact.category,
                    "category_no": f"{category_index[fact.category]:02d}",
                    "topic": fact.topic,
                    "question": question,
                    "answer": answer,
                    "tag": fact.tag,
                    "rule": fact.rule,
                }
            )
    return entries


def select_answer(fact: Fact, question: str, index: int) -> str:
    if len(fact.answers) == 5:
        return fact.answers[index]

    q = question.replace(" ", "")
    reflective_markers = (
        "하고싶",
        "어때",
        "어울",
        "된다면",
        "가능",
        "고르면",
        "한마디",
        "말하고싶",
        "바꾸",
        "달라",
        "싫어",
        "무서워",
        "마지막",
        "견뎌",
        "어떡해",
        "기다려",
    )
    explanation_markers = (
        "왜",
        "이유",
        "뜻",
        "어떻게",
        "어떤",
        "한줄",
        "한마디",
        "느낌",
        "영향",
        "계기",
        "의미",
        "중요",
        "방식",
    )

    if len(fact.answers) >= 3 and any(marker in q for marker in reflective_markers):
        return fact.answers[2]
    if len(fact.answers) >= 2 and any(marker in q for marker in explanation_markers):
        return fact.answers[1]
    return fact.answers[0]


