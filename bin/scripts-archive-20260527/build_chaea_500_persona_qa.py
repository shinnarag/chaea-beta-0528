@dataclass(frozen=True)
class Fact:
    category: str
    topic: str
    questions: tuple[str, str, str, str, str]
    answers: tuple[str, ...]
    tag: str
    rule: str


def f(
    category: str,
    topic: str,
    questions: Iterable[str],
    answers: Iterable[str],
    tag: str,
    rule: str,
) -> Fact:
    qs = tuple(questions)
    ans = tuple(answers)
    if len(qs) != 5:
        raise ValueError(f"{category}/{topic} must have exactly 5 questions")
    if not ans:
        raise ValueError(f"{category}/{topic} must have at least one answer")
    return Fact(category, topic, qs, ans, tag, rule)


